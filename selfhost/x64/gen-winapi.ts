// Writes x64/winapi.hla: the names exported by msvcrt.dll, kernel32.dll and user32.dll, taken
// from src/asm/coff/winapi.ts (which tools/gen-winapi.ts reads from the Windows DLLs).
//   node x64/gen-winapi.ts            (from selfhost/)
import { writeFileSync } from 'node:fs';
import { SYSTEM_DLLS, systemExports } from '../../src/asm/coff/winapi.ts';

const DIGITS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ';
const packed = SYSTEM_DLLS.map((d) => {
  let prev = '';
  const out: string[] = [];
  for (const n of systemExports(d)) {
    let k = 0;
    while (k < prev.length && k < n.length && prev[k] === n[k] && k < DIGITS.length - 1) k++;
    out.push(DIGITS[k] + n.slice(k));
    prev = n;
  }
  return out.join(',');
});
const quote = (s: string) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
writeFileSync('x64/winapi.hla', `// x64/winapi.hla — generated by x64/gen-winapi.ts from src/asm/coff/winapi.ts. Do not edit.
// The names exported by the system DLLs the PE linker imports from, front-coded: every entry
// starts with a digit (0-9a-zA-Z) giving how many leading characters it shares with the one before.

rodata dll_names: ptr = [${SYSTEM_DLLS.map(quote).join(', ')}]

rodata dll_packed: ptr = [
${packed.map((p) => '    ' + quote(p)).join(',\n')}
]
`);
console.log(SYSTEM_DLLS.map((d, i) => `${d}: ${systemExports(d).size} names, ${packed[i].length} bytes`).join('\n'));
