// Writes src/asm/elf/glibc.ts: the names exported by libc.so.6 and libm.so.6 of glibc for x86-64 Linux,
// read from the dynamic symbol tables of the stub libraries zig builds for `-target x86_64-linux-gnu.2.35`
// (glibc 2.35: Ubuntu 22.04; newer systems export everything it does). The ELF linker uses them to put the
// right libraries in DT_NEEDED, to reject names neither library has and to ask for the default version of
// every symbol (what ld records: memcpy@GLIBC_2.14, realpath@GLIBC_2.3); data symbols (stdout, environ…) are
// listed apart, since a program reaches them through the GOT and never calls them. The generated file is
// committed; run this to refresh it (needs zig): node tools/gen-glibc.ts
import { readFileSync, writeFileSync, mkdtempSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir, homedir } from 'node:os';
import { spawnSync } from 'node:child_process';

const GLIBC = '2.35';
const LIBS = ['libc.so.6', 'libm.so.6'];

// make zig build (or reuse) the stubs, then find the newest cache directory that has them
const tmp = mkdtempSync(join(tmpdir(), 'gen-glibc-'));
writeFileSync(join(tmp, 'm.c'), '#include <math.h>\nint main(void) { return (int)sin(1.0); }\n');
const r = spawnSync('zig', ['cc', '-target', `x86_64-linux-gnu.${GLIBC}`, join(tmp, 'm.c'), '-lm', '-o', join(tmp, 'm')], { encoding: 'utf8' });
if (r.status !== 0) throw new Error(`zig cc failed: ${r.stderr || r.error}`);
const caches = [process.env.ZIG_GLOBAL_CACHE_DIR, join(homedir(), '.cache', 'zig'), join(homedir(), 'Library', 'Caches', 'zig')]
  .filter((d): d is string => !!d && existsSync(join(d, 'o')));
let dir = '', newest = 0;
for (const c of caches) for (const d of readdirSync(join(c, 'o'))) {
  const p = join(c, 'o', d, 'libc.so.6');
  if (!existsSync(p) || !existsSync(join(c, 'o', d, 'libm.so.6')) || !isX64(p)) continue;
  // the stubs for this glibc version define nothing newer than it
  const t = statSync(p).mtimeMs;
  if (versions(p).every((v) => cmpVer(v, GLIBC) <= 0) && t > newest) { newest = t; dir = join(c, 'o', d); }
}
if (!dir) throw new Error('no glibc stubs found in the zig cache');

function cmpVer(a: string, b: string): number {
  const x = a.split('.').map(Number), y = b.split('.').map(Number);
  for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) - (y[i] ?? 0);
  return 0;
}

interface Dyn { name: string; data: boolean; version: string; hidden: boolean }
function isX64(file: string): boolean {
  const b = readFileSync(file);
  return b[4] === 2 && b.readUInt16LE(0x12) === 62;   // ELFCLASS64, EM_X86_64
}

function dynsyms(file: string): Dyn[] {
  const b = readFileSync(file);
  const shoff = Number(b.readBigUInt64LE(0x28)), shentsize = b.readUInt16LE(0x3a), shnum = b.readUInt16LE(0x3c);
  const sh = Array.from({ length: shnum }, (_, i) => {
    const o = shoff + i * shentsize;
    return { type: b.readUInt32LE(o + 4), off: Number(b.readBigUInt64LE(o + 0x18)), size: Number(b.readBigUInt64LE(o + 0x20)), link: b.readUInt32LE(o + 0x28) };
  });
  const dynsym = sh.find((s) => s.type === 11)!, strtab = sh[dynsym.link];
  const versym = sh.find((s) => s.type === 0x6fffffff), verdef = sh.find((s) => s.type === 0x6ffffffd);
  const str = (o: number) => b.toString('latin1', strtab.off + o, b.indexOf(0, strtab.off + o));
  const vnames = new Map<number, string>();
  if (verdef) {
    for (let o = verdef.off; ;) {
      const ndx = b.readUInt16LE(o + 4), aux = b.readUInt32LE(o + 12), next = b.readUInt32LE(o + 16);
      vnames.set(ndx, str(b.readUInt32LE(o + aux)));
      if (!next) break;
      o += next;
    }
  }
  const out: Dyn[] = [];
  for (let i = 1; i < dynsym.size / 24; i++) {
    const o = dynsym.off + i * 24;
    const info = b[o + 4], shndx = b.readUInt16LE(o + 6);
    const bind = info >> 4, type = info & 15;
    if (!shndx || (bind !== 1 && bind !== 2) || (type !== 1 && type !== 2 && type !== 10 && type !== 6)) continue;
    const v = versym ? b.readUInt16LE(versym.off + 2 * i) : 1;
    out.push({ name: str(b.readUInt32LE(o)), data: type === 1 || type === 6, version: (vnames.get(v & 0x7fff) ?? '').replace(/^GLIBC_/, ''), hidden: (v & 0x8000) !== 0 });
  }
  return out;
}
function versions(file: string): string[] {
  return dynsyms(file).map((s) => s.version).filter((v) => /^\d/.test(v));
}

const DIGITS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ';
function pack(names: string[]): string {
  const sorted = [...new Set(names)].sort();
  let prev = '';
  return sorted.map((n) => {
    let k = 0;
    while (k < Math.min(prev.length, n.length, DIGITS.length - 1) && prev[k] === n[k]) k++;
    prev = n;
    return DIGITS[k] + n.slice(k);
  }).join(',');
}

const lines = [
  `// Generated by tools/gen-glibc.ts from the dynamic symbol tables of glibc ${GLIBC} (x86-64). Do not edit.`,
  '// Names exported by the libraries the ELF linker links against, front-coded: every entry starts with a digit',
  '// (0-9a-zA-Z) giving how many leading characters it shares with the previous name, grouped by the default',
  '// version of the symbol (GLIBC_<key>). `data` lists the variables (stdout, environ…), the rest are functions.',
  `const DIGITS = '${DIGITS}';`,
  'const PACKED: Record<string, Record<string, { code: string; data: string }>> = {',
];
const seen = new Set<string>();
for (const lib of LIBS) {
  // a name both libraries define belongs to the first (libc)
  const syms = dynsyms(join(dir, lib)).filter((s) => !s.name.startsWith('_') || /^(__errno_location|__ctype_b_loc|__ctype_tolower_loc|__ctype_toupper_loc|__stack_chk_fail|__assert_fail|__libc_start_main|__cxa_atexit|__cxa_finalize|__isoc99_\w+|__printf_chk|__fprintf_chk|__sprintf_chk|__snprintf_chk|__memcpy_chk|__strcpy_chk)$/.test(s.name));
  // only the default (non-hidden) definition of a name can be linked to; compatibility-only names are left out
  const fresh = syms.filter((s) => !s.hidden && /^\d/.test(s.version) && !seen.has(s.name));
  for (const s of fresh) seen.add(s.name);
  const versions = [...new Set(fresh.map((s) => s.version))].sort(cmpVer);
  lines.push(`  '${lib}': {`);
  for (const v of versions) {
    const at = fresh.filter((s) => s.version === v);
    lines.push(`    '${v}': { code: '${pack(at.filter((s) => !s.data).map((s) => s.name))}', data: '${pack(at.filter((s) => s.data).map((s) => s.name))}' },`);
  }
  lines.push('  },');
  console.log(`${lib}: ${fresh.filter((s) => !s.data).length} functions, ${fresh.filter((s) => s.data).length} variables, ${versions.length} versions`);
}
lines.push('};', '', `/** the libraries in the order the linker searches them */
export const GLIBC_LIBS = Object.keys(PACKED);

const cache = new Map<string, Map<string, { data: boolean; version: string }>>();
function unpack(s: string): Set<string> {
  const set = new Set<string>();
  let prev = '';
  for (const e of s.split(',')) {
    if (!e) continue;
    prev = prev.slice(0, DIGITS.indexOf(e[0])) + e.slice(1);
    set.add(prev);
  }
  return set;
}
/** What a glibc library exports: name -> variable or function, and its default version (GLIBC_2.14) */
export function glibcExports(lib: string): Map<string, { data: boolean; version: string }> {
  let e = cache.get(lib);
  if (!e) {
    e = new Map();
    for (const [v, { code, data }] of Object.entries(PACKED[lib] ?? {})) {
      for (const n of unpack(code)) e.set(n, { data: false, version: 'GLIBC_' + v });
      for (const n of unpack(data)) e.set(n, { data: true, version: 'GLIBC_' + v });
    }
    cache.set(lib, e);
  }
  return e;
}

/** The glibc library that defines \`name\`, whether it is a variable and its default version, or null. */
export function glibcLibraryOf(name: string): { lib: string; data: boolean; version: string } | null {
  for (const lib of GLIBC_LIBS) {
    const d = glibcExports(lib).get(name);
    if (d) return { lib, ...d };
  }
  return null;
}
`);
writeFileSync('src/asm/elf/glibc.ts', lines.join('\n'));
console.log(`wrote src/asm/elf/glibc.ts (stubs from ${dir})`);
