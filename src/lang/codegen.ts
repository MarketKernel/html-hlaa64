const MNEMONIC: Record<string, string> = { '+': 'add', '-': 'sub', '&': 'and', '|': 'orr', '^': 'eor' };

function condCode(op: string, unsigned: boolean): string {
  switch (op) {
    case '==': return 'eq';
    case '!=': return 'ne';
    case '<': return unsigned ? 'lo' : 'lt';
    case '<=': return unsigned ? 'ls' : 'le';
    case '>': return unsigned ? 'hi' : 'gt';
    case '>=': return unsigned ? 'hs' : 'ge';
  }
  throw new Error('bad comparison ' + op);
}




function subSp(n: number): string[] {
  if (isAddImm(BigInt(n))) return [`    sub sp, sp, #${n}`];
  return [...movSequence('x16', BigInt(n)).map((l) => '    ' + l), '    sub sp, sp, x16'];
}

function postless(mode: string): string {
  return mode;
}


/** Remove `b L` immediately followed by `L:` and unreachable code after unconditional branches. */
function peephole(lines: string[]): string[] {
  const out: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i].trim();
    const m = /^b (\S+)$/.exec(l);
    if (m) {
      // skip if the next non-comment line is the target label
      let j = i + 1;
      let found = false;
      while (j < lines.length && lines[j].endsWith(':')) {
        if (lines[j] === `${m[1]}:`) { found = true; break; }
        j++;
      }
      if (found) continue;
      out.push(lines[i]);
      // drop dead instructions up to the next label
      while (i + 1 < lines.length && !lines[i + 1].endsWith(':') && !lines[i + 1].trim().startsWith('.') && !lines[i + 1].trim().startsWith('//')) i++;
      continue;
    }
    out.push(lines[i]);
  }
  return out;
}





export function isFmovImm(v: number): boolean {
  for (let n = 16; n <= 31; n++) {
    for (let e = -3; e <= 4; e++) {
      const x = (n / 16) * 2 ** e;
      if (x === Math.abs(v) && v !== 0) return true;
    }
  }
  return false;
}

function fmtFloat(v: number): string {
  const s = v.toString();
  return s.includes('.') || s.includes('e') ? s : s + '.0';
}
